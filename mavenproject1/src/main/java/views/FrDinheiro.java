    private void txtEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtEnviarActionPerformed
    try {
        String nome = txtNome.getText().trim();
        String valorTexto = txtValor.getText().replace(",", ".").trim();
        
        if (nome.isEmpty() || valorTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        double valor = Double.parseDouble(valorTexto);
        
        // Salvando direto com o valor informado
        controller.DinheiroController controller = new controller.DinheiroController();
        // Se não tiver valor recebido separado, salvamos o valor e troco 0 por enquanto
        controller.registrarPagamentoDinheiro(nome, valor, valor);
        
        javax.swing.JOptionPane.showMessageDialog(this, "Pagamento em Dinheiro registrado com sucesso!");
        
        txtNome.setText("");
        txtValor.setText("");
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite um valor numérico válido.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar no banco: " + e.getMessage(), "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_txtEnviarActionPerformed

